/* =========================================================
   config.js ― アプリ全体の「設定値」をまとめたファイル
   ---------------------------------------------------------
   ・アプリ名を変えたいときは APP_NAME を書き換えるだけでOK。
   ・色の分類（暗い／明るい・低彩度／高彩度など）の境目もここで調整できます。
     数字はすべて 0〜100 の目盛りです。
   ========================================================= */

const CONFIG = {
  // ---- アプリ名（画面の左上とブラウザのタブに出る） ----
  APP_NAME: 'PALETTE LOG',

  // ---- サムネイル（ギャラリー表示用の軽い画像） ----
  THUMB_MAX: 640, // 長い辺のピクセル数
  THUMB_QUALITY: 0.86, // JPEGの画質（0〜1）

  // ---- 色の抽出 ----
  COLOR_SAMPLE_MAX: 96, // 色を数えるために縮める大きさ（小さいほど速い）
  PALETTE_SIZE: 5, // 主要色の数

  // ---- 色の分類の境目（0〜100） ----
  DARK_BELOW: 42, // 平均明度がこれ未満なら「暗い」
  BRIGHT_FROM: 64, // 平均明度がこれ以上なら「明るい」
  LOW_SAT_BELOW: 16, // 平均彩度がこれ未満なら「低彩度」
  HIGH_SAT_FROM: 34, // 平均彩度がこれ以上なら「高彩度」
  HUE_SHARE_MIN: 0.25, // 色みのうち、この割合以上を占めた色系を「〇〇系」とする

  // ---- 日付 ----
  // ファイルの更新日時が「取り込んだ時刻」とこの秒数以内に近いときは信用しない
  // （スマホで写真を選ぶと、選んだ瞬間の時刻が付くことがあるため）
  FILE_DATE_DISTRUST_SEC: 180,
};

document.title = CONFIG.APP_NAME;
